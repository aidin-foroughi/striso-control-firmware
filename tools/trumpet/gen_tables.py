"""Generate dsp/include/striso_dsp/trumpet_bore.h from the TMM fits (fit_bore.py). Needs numpy, scipy.
usage: python gen_tables.py <out.h>"""
import sys
import numpy as np
import bore
import fit_bore as fb

FS = fb.FS
# valve tubing: lengths that lower the open horn by 1, 2, 3 semitones at its nominal pitch
VALVE_SEMIS = [2, 1, 3]       # valve 1, 2, 3
COMBOS = [(), (2,), (1,), (1, 2), (2, 3), (1, 3), (1, 2, 3)]
NK = 17                        # partial index 1..16 (0 unused)


def model_peaks(inst, fit, extra_samples):
    """impedance peaks of the real-time model with extra one-way cylinder delay (samples)"""
    f = np.arange(30, 2200, 0.25)
    w = 2 * np.pi * f
    secs = fit['secs']
    A, B, C, D = fb.chain_lossless(secs, f)
    h = fit['h']
    Hd = np.interp(f, fit['f'], np.real(fit['HdHi'])) + 1j * np.interp(f, fit['f'], np.imag(fit['HdHi']))
    Hm = (np.exp(-1j * np.outer(w, np.arange(len(h)) * fb.DEC / FS)) @ h) * Hd
    loss = fit['vloss'] ** extra_samples
    Rm = Hm * np.exp(-2j * w * (fit['dpure'] + extra_samples) / FS) * loss
    Zw = fit['Zw']
    ZL = Zw * (1 + Rm) / (1 - Rm)
    zt = (A * ZL + B) / (C * ZL + D)
    Cc = inst.V / (bore.RHO * bore.C0 ** 2)
    z = 1 / (1j * w * Cc + 1 / zt)
    return bore.peaks(f, z, 40, 2150)


def fmt(a, per=8):
    a = list(a)
    lines = []
    for i in range(0, len(a), per):
        lines.append('    ' + ', '.join(f'{x:.9g}f' for x in a[i:i + per]) + ',')
    return '\n'.join(lines)


def main(outp):
    insts = fb.make_insts()
    out = []
    out.append('// Generated by gen_tables.py (scratchpad trumpet/), do not edit: the bores of voice_trumpet.h,')
    out.append('// fitted to transmission-line (TMM) models of real bore profiles with visco-thermal losses and an')
    out.append('// unflanged radiation load (Silva et al. 2009). Internal rate 96 kHz (2x the board rate).')
    out.append('#ifndef TRUMPET_BORE_H_')
    out.append('#define TRUMPET_BORE_H_')
    out.append('// clang-format off')
    out.append('namespace trumpet::bore {')
    out.append(f'static constexpr int FS = {FS};')
    out.append(f'static constexpr int DEC = {fb.DEC};')
    out.append(f'static constexpr int NDEC = {fb.NDEC};')
    out.append(f'static constexpr int NFIR = {fb.NFIR};')
    out.append(f'static constexpr int NK = {NK};')
    out.append('static constexpr int NCOMBO = 7;')
    out.append('static constexpr int MAXSEC = 8;')
    out.append(f'// decimator (96 -> 12 kHz, gain 1) and interpolator (12 -> 96 kHz) FIR, linear phase')
    out.append(f'static constexpr float HDEC[NDEC] = {{\n{fmt(fb.HDEC)}\n}};')
    out.append(f'static constexpr float HINT[NDEC] = {{\n{fmt(fb.HINT)}\n}};')
    out.append('struct Bore {')
    out.append('    const char* name;')
    out.append('    int nsec;               // front-end sections (throat, backbore, leadpipe)')
    out.append('    int sec_d[MAXSEC];      // their delays (samples at 96 kHz)')
    out.append('    float sec_k[MAXSEC];    // pressure reflection coefficient of the junction after section i')
    out.append('    float z0;               // characteristic impedance of the throat (Pa s / m^3)')
    out.append('    float cup_v;            // nominal cup volume (m^3)')
    out.append('    float dpure;            // cylinder one-way pure delay at the nominal slide (samples)')
    out.append('    float valve_d[3];       // one-way delay of valve 1, 2, 3 tubing (samples)')
    out.append('    float vloss;            // loss per sample of added tubing (one way)')
    out.append('    float f_nom;            // nominal fundamental (Hz) of the open horn')
    out.append('    float bell_r;           // bell mouth radius (m)')
    out.append('    float res_c[NCOMBO][NK];  // resonance k of each combination: cents re k * f_nom (pedal: k = 1)')
    out.append('    float rad_g;            // radiation (bell entry wave -> far field) at 48 kHz: gain and 3 biquads')
    out.append('    float rad[3][4];        //   b1, b2, a1, a2 (b0 = 1)')
    out.append('    float fir[NFIR];        // bell reflection at 12 kHz (the losses of the whole bore included)')
    out.append('};')
    out.append(f'static constexpr int NBORE = {len(insts)};')
    out.append('static constexpr Bore BORES[NBORE] = {')
    for inst in insts:
        fb.tune_length(inst)
        fit = fb.fit_inst(inst, verbose=True)
        secs = fit['secs']
        assert len(secs) <= 7 and max(n for n, r in secs) < 32, secs
        Z = [bore.RHO * bore.C0 / (np.pi * r * r) for (n, r) in secs] + [fit['Zw']]
        ks = [(Z[i + 1] - Z[i]) / (Z[i + 1] + Z[i]) for i in range(len(secs))]
        Le = bore.C0 / (2 * inst.f_nom)
        vd = [Le * (2 ** (s / 12) - 1) / bore.C0 * FS for s in VALVE_SEMIS]
        # wall loss of added cylinder tubing at ~500 Hz (Benade: alpha = 2.96e-5 sqrt(f) / r per m)
        alpha = 2.96e-5 * np.sqrt(500) / inst.r_bore
        vloss = np.exp(-alpha * bore.C0 / FS)
        fit['vloss'] = vloss
        res = np.zeros((7, NK))
        for ci, cb in enumerate(COMBOS):
            ext = sum(vd[{1: 0, 2: 1, 3: 2}[v]] for v in cb)
            pk = model_peaks(inst, fit, ext)
            semis = 12 * np.log2((Le + sum(Le * (2 ** (VALVE_SEMIS[{1: 0, 2: 1, 3: 2}[v]] / 12) - 1) for v in cb)) / Le)
            fbase = inst.f_nom * 2 ** (-semis / 12)
            for k in range(1, NK):
                c = [p for p, a in pk if abs(p / (k * fbase) - 1) < (0.3 if k == 1 else 0.06)]
                if k == 1:
                    c = [p for p, a in pk if p < 0.9 * fbase]
                res[ci, k] = 1200 * np.log2(c[0] / (k * inst.f_nom * 2 ** (-sum(VALVE_SEMIS[{1: 0, 2: 1, 3: 2}[v]] for v in cb) / 12))) if c else 999.0
                if abs(res[ci, k]) > 90 and k > 1:
                    res[ci, k] = 999.0   # not a usable resonance
            # pedal tone: a privileged frequency (lips lock with harmonics 2, 3, 4 on resonances 2, 3, 4)
            res[ci, 1] = res[ci, 2] if res[ci, 2] < 900 else 999.0
            print('  combo', cb, ' '.join(f'{x:5.0f}' for x in res[ci, 1:]))
        f, T = fb.radiation(inst)
        g, rs, rms = fb.fit_minphase_iir(f, T, 48000)
        print(f'  radiation fit rms {rms:.2f} dB')
        lines = [f'    {{"{inst.name}", {len(secs)}, {{{", ".join(str(n) for n, r in secs)}}},',
                 f'     {{{", ".join(f"{k:.9g}f" for k in ks)}}},',
                 f'     {Z[0]:.9g}f, {inst.V:.9g}f, {fit["dpure"]:.9g}f, {{{", ".join(f"{x:.9g}f" for x in vd)}}}, {vloss:.9g}f, {inst.f_nom:.9g}f, {inst.bell[-1][2]:.6g}f,',
                 '     {' + ',\n      '.join('{' + ', '.join(f'{x:.2f}f' for x in row) + '}' for row in res) + '},',
                 f'     {g:.9g}f, {{' + ', '.join('{' + ', '.join(f'{x:.9g}f' for x in s[1:]) + '}' for s in rs) + '},',
                 f'     {{\n{fmt(fit["h"])}\n     }}}},']
        out.extend(lines)
    out.append('};')
    out.append('} // namespace trumpet::bore')
    out.append('// clang-format on')
    out.append('#endif')
    open(outp, 'w', newline='\n').write('\n'.join(out) + '\n')


main(sys.argv[1])
