"""gen_cal.py out.h cal_p0.json .. cal_p8.json: trumpet_cal.h from the cal.py results (one per preset)"""
import sys, json, numpy as np
LO = [40, 40, 42, 52, 40, 40, 40, 40, 40]
N = 55
def fill(v):
    v = np.array(v, float); ok = np.isfinite(v); idx = np.arange(len(v))
    return np.interp(idx, idx[ok], v[ok])
rows = []
for pi, fn in enumerate(sys.argv[2:]):
    d = json.load(open(fn)); lo = LO[pi]
    get = lambda k: fill([d.get(str(lo + i), {}).get(k, np.nan) for i in range(N)])
    rows.append((lo, get('trim'), get('lip'), get('pthr')))
f = lambda a: '{' + ', '.join(f'{x:.1f}f' for x in a) + '}'
out = ['// Generated by tools/trumpet/cal/gen_cal.py from tools/trumpet/cal/cal.py runs, do not edit: per preset and note',
       '// (index = note - lo), measured on the host with the engine itself (two-mode lips): how the player sets',
       '// the lips (cents re the default setting, 0.92 x the note), the slide trim the note settles at',
       '// (cents) and the mouth pressure (Pa) from which the note speaks.',
       '#ifndef TRUMPET_CAL_H_', '#define TRUMPET_CAL_H_', '// clang-format off', 'namespace trumpet::cal {',
       f'static constexpr int NCAL = {N};', 'struct Cal {', '    float lo;', '    float trim[NCAL];', '    float lip[NCAL];', '    float pthr[NCAL];', '};',
       f'static constexpr Cal CAL[{len(rows)}] = {{']
for lo, t, l, p in rows:
    out.append(f'    {{{lo:.1f}f,\n     {f(t)},\n     {f(l)},\n     {f(p)}}},')
out += ['};', '} // namespace trumpet::cal', '// clang-format on', '#endif']
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')
