"""trumpet_seed.h from capture lines: python gen_seed.py out.h caps.txt [presets lo-hi ...]
caps.txt: CAP lines of cap.cpp (any order). Per preset the note range covers the captured notes;
missing / failed states are marked ok = 0."""
import sys, math, collections
NH, NDYN, NSIG = 6, 3, 5   # as captured
NHO = 4                    # harmonics kept in the table
RANGE = {0: (43, 74), 1: (43, 74), 2: (45, 74), 3: (58, 82), 4: (43, 74), 5: (43, 74), 6: (43, 74), 7: (43, 74), 8: (43, 74)}
DYN = [0.3, 0.55, 0.8]
NPRESET = 9
outp, capf = sys.argv[1], sys.argv[2]
caps = {}
for line in open(capf):
    t = line.split()
    if not t or t[0] != 'CAP': continue
    pr, note, d, ok = int(t[1]), int(t[2]), int(t[3]), int(t[4])
    per, trim, um = map(float, t[5:8])
    combo, k, ext = map(int, t[8:11])
    v = list(map(float, t[11:]))
    dc = v[:NSIG]
    h = v[NSIG:]
    re = [[h[(q * NH + i) * 2] for i in range(NH)] for q in range(NSIG)]
    im = [[h[(q * NH + i) * 2 + 1] for i in range(NH)] for q in range(NSIG)]
    caps[(pr, note, d)] = dict(ok=ok, per=per, trim=trim, um=um, combo=combo, k=k, ext=ext, dc=dc, re=re, im=im)
def f(x):
    if x != x: return '0.0f'
    t = f'{x:.6g}'
    if '.' not in t and 'e' not in t: t += '.0'
    return t + 'f'
out = ['// Generated by tools/trumpet/warm (cap.cpp, gen_seed.py), do not edit: the warm start',
       '// of voice_trumpet.h. Per preset and note (index = note - lo) and breath DYN (key pressure units): the',
       '// steady oscillation the model itself settles in after a tongued start (one period, as the mean and',
       '// the first NH harmonics, phase 0 = the lip opening\'s fundamental at its crest) of the cylinder\'s',
       '// forward input, the bell reflection (Pa), the cup pressure (Pa) and the two lip modes (m); the period',
       '// (samples at 96 kHz), the slide trim (cents) and the mean jet flow it settled at, and its fingering.',
       '#ifndef TRUMPET_SEED_H_', '#define TRUMPET_SEED_H_', '#include <stdint.h>', '// clang-format off', 'namespace trumpet::seed {',
       f'static constexpr int NH = {NHO};', f'static constexpr int NDYN = {NDYN};',
       f'static constexpr int NSIG = {NSIG}; // cylinder forward input, bell reflection, cup pressure, lip modes out / in',
       'static constexpr float DYN[NDYN] = {' + ', '.join(f'{d}f' for d in DYN) + '};',
       'struct State {', '    float per, trim, um;', '    float dc[NSIG];', '    float re[NSIG][NH], im[NSIG][NH];', '    int8_t combo, k, ext, ok;', '};',
       'struct Set {', '    int lo, n;', '    const State* st;', '};',
       'static constexpr float COS64[64] = {' + ', '.join(f(round(math.cos(2 * math.pi * j / 64), 9)) for j in range(64)) + '};']
sets = []
for pr in range(NPRESET):
    notes = sorted({n for (p, n, d) in caps if p == pr and RANGE[pr][0] <= n <= RANGE[pr][1]})
    if not notes:
        sets.append('{0, 0, nullptr}'); continue
    lo, hi = notes[0], notes[-1]
    rows = []
    for n in range(lo, hi + 1):
        for d in range(NDYN):
            c = caps.get((pr, n, d))
            if c is None or not c['ok']:
                rows.append('    {0.0f, 0.0f, 0.0f, {}, {}, {}, 0, 0, 0, 0},'); continue
            dc = '{' + ', '.join(f(x) for x in c['dc']) + '}'
            re = '{' + ', '.join('{' + ', '.join(f(x) for x in r[:NHO]) + '}' for r in c['re']) + '}'
            im = '{' + ', '.join('{' + ', '.join(f(x) for x in r[:NHO]) + '}' for r in c['im']) + '}'
            rows.append(f"    {{{f(c['per'])}, {f(c['trim'])}, {f(c['um'])}, {dc}, {re}, {im}, {c['combo']}, {c['k']}, {c['ext']}, 1}}, // {n} {DYN[d]}")
    out.append(f'static constexpr State ST{pr}[{len(rows)}] = {{')
    out += rows
    out.append('};')
    sets.append(f'{{{lo}, {hi - lo + 1}, ST{pr}}}')
out.append(f'static constexpr Set SETS[{NPRESET}] = {{' + ', '.join(sets) + '};')
out += ['} // namespace trumpet::seed', '// clang-format on', '#endif']
open(outp, 'w', newline='\n').write('\n'.join(out) + '\n')
nok = sum(c['ok'] for c in caps.values())
import os
print(f'{os.path.getsize(outp)} bytes of source', file=sys.stderr)
print(f'{len(caps)} states, {nok} ok', file=sys.stderr)
