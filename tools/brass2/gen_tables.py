"""Generate dsp/include/striso_dsp/brass2_bore.h: the bores of voice_brass2.h (the brass family on the
shared core, brass_core.h), fitted with the trumpet's TMM tools (tools/trumpet/bore.py, fit_bore.py).
Needs numpy, scipy.  usage: python gen_tables.py <out.h>

Per bore: the front end (Kelly-Lochbaum sections), the cylinder's pure delay, the bell reflection FIR
(12 kHz, NFIR taps), the radiation filter, the valve / trigger tubing, and the resonance chart:
  res_c[c][k]: resonance k of valve (trigger) combination c, cents re k * f_nom * 2^(-semis(c)/12)
  res_u[u][k]: resonance k with u semitones of added length (slide + triggers), cents re
               k * f_nom * 2^(-u/12); the engine interpolates it for a slide's continuous length.
"""
import os
import sys
import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'trumpet'))
import bore  # noqa: E402
import fit_bore as fb  # noqa: E402

FS = fb.FS
NFIR = 192
NK = 17   # partial index 1..16 (0 unused)
NU = 14   # added length 0..13 semitones
NCOMBO = 7
# combinations of valves 1, 2, 3: trumpet-style valve instruments (later) and the trombone triggers
# (valve 1 = F attachment, valve 2 = the second trigger (Gb), 1 + 2 = D)
COMBOS = [(), (2,), (1,), (1, 2), (2, 3), (1, 3), (1, 2, 3)]
TRIG_COMBOS = [(), (1,), (2,), (1, 2)]


class Inst(fb.Inst):
    def __init__(self, name, front, Lc, bell, r_bore, V, f_nom, slide, valve_semis, ncombo, slide_max):
        super().__init__(name, front, Lc, bell, r_bore, V, f_nom)
        self.slide, self.valve_semis, self.ncombo, self.slide_max = slide, valve_semis, ncombo, slide_max


def make_insts():
    out = []
    # tenor trombone, Bb/F, large bore 0.547" (13.9 mm), 8.5" bell; mouthpiece ~6.5AL: 6.6 mm throat
    rb = 6.95e-3
    fr = [(0.007, 3.3e-3, 3.3e-3), (0.075, 3.3e-3, 4.6e-3), (0.23, 4.7e-3, rb)]
    bl = [(0.30, 7.0e-3, 8.5e-3)] + bore.bessel_bell(0.80, 8.5e-3, 108e-3, 0.7)
    out.append(Inst('tenor', fr, 1.41, bl, rb, 2.6e-6, 466.16 / 8, 1, [5, 4, 0], 2, 6.4))
    # bass trombone, Bb/F/Gb/D independent, 0.562" (14.3 mm), 9.5" bell; mouthpiece ~1.5G: 7.3 mm throat
    rb = 7.14e-3
    fr = [(0.008, 3.65e-3, 3.65e-3), (0.08, 3.65e-3, 5.0e-3), (0.24, 5.1e-3, rb)]
    bl = [(0.30, 7.3e-3, 9.0e-3)] + bore.bessel_bell(0.85, 9.0e-3, 120e-3, 0.7)
    out.append(Inst('bass', fr, 1.38, bl, rb, 3.4e-6, 466.16 / 8, 1, [5, 4, 0], 4, 6.4))
    return out


def model_peaks(inst, fit, extra_samples, fmax=2150):
    """impedance peaks of the real-time model with extra one-way cylinder delay (samples)"""
    f = np.arange(20, fmax, 0.25)
    w = 2 * np.pi * f
    A, B, C, D = fb.chain_lossless(fit['secs'], f)
    h = fit['h']
    Hd = np.interp(f, fit['f'], np.real(fit['HdHi'])) + 1j * np.interp(f, fit['f'], np.imag(fit['HdHi']))
    Hm = (np.exp(-1j * np.outer(w, np.arange(len(h)) * fb.DEC / FS)) @ h) * Hd
    Rm = Hm * np.exp(-2j * w * (fit['dpure'] + extra_samples) / FS) * fit['vloss'] ** (2 * extra_samples)
    Zw = fit['Zw']
    ZL = Zw * (1 + Rm) / (1 - Rm)
    zt = (A * ZL + B) / (C * ZL + D)
    Cc = inst.V / (bore.RHO * bore.C0 ** 2)
    z = 1 / (1j * w * Cc + 1 / zt)
    return bore.peaks(f, z, 18, fmax - 50)


def res_row(inst, fit, Le, semis):
    """cents of resonances 1..NK-1 re k * f_nom * 2^(-semis/12), with the length that lowers the open horn by semis"""
    ext = Le * (2 ** (semis / 12) - 1) / bore.C0 * FS
    pk = model_peaks(inst, fit, ext)
    fbase = inst.f_nom * 2 ** (-semis / 12)
    row = np.zeros(NK)
    for k in range(1, NK):
        c = [p for p, a in pk if abs(p / (k * fbase) - 1) < 0.06]
        row[k] = 1200 * np.log2(c[0] / (k * fbase)) if c else 999.0
        if abs(row[k]) > 90 and k > 1:
            row[k] = 999.0
    # pedal tone: a privileged frequency (lips lock with harmonics 2, 3, 4 on resonances 2, 3, 4)
    row[1] = row[2] if row[2] < 900 else 999.0
    return row


def fmt(a, per=8):
    a = list(a)
    return '\n'.join('    ' + ', '.join(f'{x:.9g}f' for x in a[i:i + per]) + ',' for i in range(0, len(a), per))


def main(outp):
    insts = make_insts()
    o = []
    o.append('// Generated by tools/brass2/gen_tables.py, do not edit: the bores of voice_brass2.h, fitted to')
    o.append('// transmission-line (TMM) models of real bore profiles with visco-thermal losses and an unflanged')
    o.append('// radiation load (Silva et al. 2009; tools/trumpet/bore.py). Internal rate 96 kHz (2x the board rate).')
    o.append('#ifndef BRASS2_BORE_H_')
    o.append('#define BRASS2_BORE_H_')
    o.append('// clang-format off')
    o.append('namespace brass2::bore {')
    o.append(f'static constexpr int FS = {FS};')
    o.append(f'static constexpr int DEC = {fb.DEC};')
    o.append(f'static constexpr int NDEC = {fb.NDEC};')
    o.append(f'static constexpr int NFIR = {NFIR};')
    o.append(f'static constexpr int NK = {NK};')
    o.append(f'static constexpr int NU = {NU};')
    o.append(f'static constexpr int NCOMBO = {NCOMBO};')
    o.append('static constexpr int MAXSEC = 8;')
    o.append('// decimator (96 -> 12 kHz, gain 1) and interpolator (12 -> 96 kHz) FIR, linear phase')
    o.append(f'static constexpr float HDEC[NDEC] = {{\n{fmt(fb.HDEC)}\n}};')
    o.append(f'static constexpr float HINT[NDEC] = {{\n{fmt(fb.HINT)}\n}};')
    o.append('struct Bore {')
    o.append('    const char* name;')
    o.append('    int nsec;               // front-end sections (throat, backbore, leadpipe)')
    o.append('    int sec_d[MAXSEC];      // their delays (samples at 96 kHz)')
    o.append('    float sec_k[MAXSEC];    // pressure reflection coefficient of the junction after section i')
    o.append('    float z0;               // characteristic impedance of the throat (Pa s / m^3)')
    o.append('    float cup_v;            // nominal cup volume (m^3)')
    o.append('    float dpure;            // cylinder one-way pure delay at the nominal slide (samples)')
    o.append('    float valve_d[3];       // one-way delay of valve 1, 2, 3 tubing (samples; a trombone: the triggers)')
    o.append('    float vloss;            // loss per sample of added tubing (one way, ~300 Hz)')
    o.append('    float f_nom;            // nominal fundamental (Hz) of the open horn')
    o.append('    float bell_r;           // bell mouth radius (m)')
    o.append('    int slide;              // 1: a slide instrument (continuous length), its triggers are valve 1, 2')
    o.append('    int ncombo;             // valve / trigger combinations the instrument has')
    o.append('    float slide_max;        // slide reach, semitones of added length on the open horn (7th position + a bit)')
    o.append('    float res_c[NCOMBO][NK];  // resonance k of each combination: cents re k * f_nom * 2^(-semis/12) (pedal: k = 1)')
    o.append('    float res_u[NU][NK];      // resonance k with u semitones of added length: cents re k * f_nom * 2^(-u/12)')
    o.append('    float rad_g;            // radiation (bell entry wave -> far field) at 48 kHz: gain and 3 biquads')
    o.append('    float rad[3][4];        //   b1, b2, a1, a2 (b0 = 1)')
    o.append('    float fir[NFIR];        // bell reflection at 12 kHz (the losses of the whole bore included)')
    o.append('};')
    o.append(f'static constexpr int NBORE = {len(insts)};')
    o.append('static constexpr Bore BORES[NBORE] = {')
    for inst in insts:
        fb.tune_length(inst)
        fit = fb.fit_inst(inst, nfir=NFIR, verbose=True)
        secs = fit['secs']
        assert len(secs) <= 7 and max(n for n, r in secs) < 32, secs
        Z = [bore.RHO * bore.C0 / (np.pi * r * r) for (n, r) in secs] + [fit['Zw']]
        ks = [(Z[i + 1] - Z[i]) / (Z[i + 1] + Z[i]) for i in range(len(secs))]
        Le = bore.C0 / (2 * inst.f_nom)
        vd = [Le * (2 ** (s / 12) - 1) / bore.C0 * FS + 1e-9 for s in inst.valve_semis]
        # wall loss of added cylinder tubing at ~300 Hz (Benade: alpha = 2.96e-5 sqrt(f) / r per m)
        alpha = 2.96e-5 * np.sqrt(300) / inst.r_bore
        fit['vloss'] = np.exp(-alpha * bore.C0 / FS)
        combos = TRIG_COMBOS if inst.slide else COMBOS
        res = np.full((NCOMBO, NK), 999.0)
        for ci in range(NCOMBO):
            if ci >= inst.ncombo:
                continue
            ext = sum(vd[v - 1] for v in combos[ci])
            semis = 12 * np.log2((Le / bore.C0 * FS + ext) / (Le / bore.C0 * FS))
            res[ci] = res_row(inst, fit, Le, semis)
            print('  combo', combos[ci], f'{semis:5.2f} st', ' '.join(f'{x:5.0f}' for x in res[ci, 1:]))
        resu = np.zeros((NU, NK))
        for u in range(NU):
            resu[u] = res_row(inst, fit, Le, u)
            print('  u', u, ' '.join(f'{x:5.0f}' for x in resu[u, 1:]))
        f, T = fb.radiation(inst)
        g, rs, rms = fb.fit_minphase_iir(f, T, 48000)
        print(f'  radiation fit rms {rms:.2f} dB')
        rows = lambda R: '{' + ',\n      '.join('{' + ', '.join(f'{x:.2f}f' for x in row) + '}' for row in R) + '}'
        o += [f'    {{"{inst.name}", {len(secs)}, {{{", ".join(str(n) for n, r in secs)}}},',
              f'     {{{", ".join(f"{k:.9g}f" for k in ks)}}},',
              f'     {Z[0]:.9g}f, {inst.V:.9g}f, {fit["dpure"]:.9g}f, {{{", ".join(f"{x:.9g}f" for x in vd)}}}, {fit["vloss"]:.9g}f, {inst.f_nom:.9g}f, {inst.bell[-1][2]:.6g}f,',
              f'     {inst.slide}, {inst.ncombo}, {inst.slide_max:.3g}f,',
              '     ' + rows(res) + ',',
              '     ' + rows(resu) + ',',
              f'     {g:.9g}f, {{' + ', '.join('{' + ', '.join(f'{x:.9g}f' for x in s[1:]) + '}' for s in rs) + '},',
              f'     {{\n{fmt(fit["h"])}\n     }}}},']
    o.append('};')
    o.append('} // namespace brass2::bore')
    o.append('// clang-format on')
    o.append('#endif')
    open(outp, 'w', newline='\n').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main(sys.argv[1])
